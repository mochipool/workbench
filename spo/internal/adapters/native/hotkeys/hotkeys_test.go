package hotkeys

import (
	"bytes"
	"context"
	"encoding/hex"
	"encoding/json"
	"os"
	"testing"

	"github.com/blinklabs-io/gouroboros/kes"

	"github.com/mochipool/workbench/spo/internal/platform/secret"
)

func envOf(t *testing.T, raw []byte) *secret.Buffer {
	t.Helper()
	b, _ := json.Marshal(map[string]string{"type": "KesSigningKey_ed25519_kes_2^6", "description": "d", "cborHex": "590260" + hex.EncodeToString(raw)})
	return secret.Take(b)
}

func fixture(t *testing.T) (raw []byte, vkey []byte) {
	t.Helper()
	read := func(n string) []byte {
		b, err := os.ReadFile("../testdata/kes-oracle/" + n)
		if err != nil {
			t.Fatal(err)
		}
		var e struct{ CborHex string }
		if err := json.Unmarshal(b, &e); err != nil {
			t.Fatal(err)
		}
		h, _ := hex.DecodeString(e.CborHex)
		return h
	}
	sk, vk := read("period0.skey"), read("period0.vkey")
	return sk[3:], vk[2:]
}

// A KES key generated by cardano-cli 11.2.3.0 (period 0) derives the verification
// key cardano-cli wrote with it.
//
// spec: SPO-Xcustody-PRE-009
func TestOracleKESKeyDerivesItsVerificationKey(t *testing.T) {
	raw, vk := fixture(t)
	got, err := Deriver{}.DeriveKES(context.Background(), envOf(t, raw))
	if err != nil || !bytes.Equal(got, vk) {
		t.Fatalf("%x %v", got, err)
	}
}

// Overwriting any seed of the structure (with a cold Ed25519 seed, say) while
// leaving the stored public keys alone is refused: the root key is derived from
// the secrets that are there, not read from the blob.
//
// spec: SPO-Xcustody-PRE-009
func TestKESKeyWithOverwrittenSeedsIsRefused(t *testing.T) {
	raw, _ := fixture(t)
	cold := bytes.Repeat([]byte{0x42}, 32)
	leaf := 0                             // the leaf seed
	for level := 1; level <= 6; level++ { // right seed of each level
		off := 32 + (level-1)*96
		for name, at := range map[string]int{"leaf": leaf, "right seed": off} {
			if name == "leaf" && level > 1 {
				continue
			}
			bad := append([]byte(nil), raw...)
			copy(bad[at:], cold)
			if _, err := (Deriver{}).DeriveKES(context.Background(), envOf(t, bad)); err == nil {
				t.Errorf("level %d %s overwritten: accepted", level, name)
			}
		}
	}
	// the stored public keys rewritten to match a cold leaf give another root key
	_, vk := fixture(t)
	bad := append([]byte(nil), raw...)
	copy(bad[0:], cold)
	if got, err := (Deriver{}).DeriveKES(context.Background(), envOf(t, bad)); err == nil && bytes.Equal(got, vk) {
		t.Error("the stored verification key was reproduced from a cold seed")
	}
}

// Evolved keys (the library's Update erases the spent seeds) still derive the
// root key of period 0. Only the library's own evolution backs this (the oracle
// fixture is period 0), across the first level (period 1), the middle (32, where
// the top seed is erased) and the end (63).
//
// spec: SPO-Xcustody-PRE-009
func TestEvolvedKESKeysDeriveTheSameRootKey(t *testing.T) {
	seed := bytes.Repeat([]byte{7}, 32)
	sk, pub, err := kes.KeyGen(kes.CardanoKesDepth, seed)
	if err != nil {
		t.Fatal(err)
	}
	for p := 1; p <= 63; p++ {
		if sk, err = kes.Update(sk); err != nil {
			t.Fatal(err)
		}
		if p != 1 && p != 31 && p != 32 && p != 33 && p != 63 {
			continue
		}
		got, err := Deriver{}.DeriveKES(context.Background(), envOf(t, sk.Data))
		if err != nil || !bytes.Equal(got, pub) {
			t.Errorf("period %d: %v", p, err)
		}
	}
}
